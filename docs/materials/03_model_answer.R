library(tidyverse)


# ------------------------------------------------------------
# 演習1：散布図
#   Petal.Length（x軸）と Petal.Width（y軸）の散布図を作り，
#   Species で色分けする
# ------------------------------------------------------------

ggplot(data = iris, aes(x = Petal.Length, y = Petal.Width, color = Species)) +
  geom_point()

# 問1：この図の点1つは，何を表していますか
# 　　 アヤメ1本（1個体）です。その花の「花びらの長さ」と「花びらの幅」の
# 　　 組み合わせを，1つの点の位置で表しています。
# 　　 点が150個より少なく見えるのは，同じ位置に複数の花が重なっているためです。

# 問2：3つの種のうち，他の2つとはっきり分かれている種はどれですか
# 　　 setosa です。左下にかたまっていて，他の2種とまったく重なりません。
# 　　 versicolor と virginica は境目で少し重なっています。


# ------------------------------------------------------------
# 演習2：ヒストグラム
#   Petal.Width のヒストグラム（binwidth = 0.2）に
#   タイトルと軸ラベルを付ける
# ------------------------------------------------------------

ggplot(data = iris, aes(x = Petal.Width)) +
  geom_histogram(binwidth = 0.2, fill = "steelblue", color = "white") +
  labs(
    title = "花びらの幅の分布",
    x = "花びらの幅 (cm)",
    y = "花の数"
  )

# 縦軸は Rが数えた「度数」なので，aes() で指定しません。
# ラベルは「度数」でも「花の数」でも構いません。

# 余裕があれば：binwidth を変えて見え方を比べる
#   0.1 … 山がギザギザになり，細かい凹凸が目立つ
#   0.2 … 低い山（setosa）と高い山（残り2種）の2つに分かれて見える
#   0.4 … なめらかになるが，2つの山の境目が分かりにくくなる
# 同じデータでも，binwidth の決め方で印象が変わります。

ggplot(data = iris, aes(x = Petal.Width)) +
  geom_histogram(binwidth = 0.1, fill = "steelblue", color = "white") +
  labs(title = "binwidth = 0.1", x = "花びらの幅 (cm)", y = "花の数")

ggplot(data = iris, aes(x = Petal.Width)) +
  geom_histogram(binwidth = 0.4, fill = "steelblue", color = "white") +
  labs(title = "binwidth = 0.4", x = "花びらの幅 (cm)", y = "花の数")


# ------------------------------------------------------------
# 演習3：箱ひげ図
#   種（Species）ごとに Petal.Length の分布を比べる
# ------------------------------------------------------------

ggplot(data = iris, aes(x = Species, y = Petal.Length, fill = Species)) +
  geom_boxplot() +
  labs(
    title = "種ごとの花びらの長さ",
    x = "種",
    y = "花びらの長さ (cm)"
  )

# 問：花びらの長さの中央値がいちばん大きい種はどれですか。
# 　　図のどこを見てそう判断したかも書いてください。
# 　　virginica です。箱の中の太い横線が中央値で，その線がいちばん上にあります。
# 　　中央値は setosa 1.50，versicolor 4.35，virginica 5.55 です。

# 数値でも確かめられます
tapply(iris$Petal.Length, iris$Species, median)

# setosa の箱が縦に短いのは，件数が少ないからではありません（どの種も50本です）。
# 第1四分位数から第3四分位数までの幅が狭い，つまり
# 真ん中50%のばらつきが小さい，ということです。
